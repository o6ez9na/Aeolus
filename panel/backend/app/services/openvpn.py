def render_transit_ccd(
    node: Node, *, is_exit: bool = False, site_routes: list[str] | None = None
) -> str:
    """The hub's ccd entry for one node: its address and the LANs behind it.

    An exit node also gets the default route: OpenVPN picks the peer for a
    packet by destination only, and without it drops internet-bound traffic
    that policy routing has already sent into the tunnel (see services/exits).

    ``site_routes`` are the networks of the sites this node is linked to
    (services/links): pushed to the node, so its LAN finds them through the
    transit. The hub drops a node's session when this file changes, which is
    what gets a new route to the node.
    """
    if node.transit_host is None:
        return f"# {node.name}: no transit address assigned\ndisable\n"

    lines = [
        f"# {node.name} — сгенерировано Aeolus",
        f"ifconfig-push {transit_address(node.transit_host)} {settings.vpn_netmask}",
    ]
    for subnet in node.subnets or []:
        net = ipaddress.ip_network(subnet)
        lines.append(f"iroute {net.network_address} {net.netmask}")
    if is_exit:
        lines.append("# выход в интернет для клиентов хаба")
        lines.append("iroute 0.0.0.0 0.0.0.0")
    if site_routes:
        lines.append("# связи сетей: маршруты к связанным площадкам")
        for subnet in site_routes:
            net = ipaddress.ip_network(subnet, strict=False)
            lines.append(f'push "route {net.network_address} {net.netmask}"')
    return "\n".join(lines) + "\n"


def render_client_config(client: Client, node: Node, ca: CertificateAuthority) -> str:
    """A single self-contained .ovpn file with everything inlined."""
    if client.cert_pem is None or client.key_pem_encrypted is None:
        raise OpenVpnError(
            f"{client.common_name} has no certificate yet; issue one in the pki section"
        )
    if client.revoked_at is not None:
        raise OpenVpnError(f"{client.common_name} is revoked")

    key_pem = decrypt_secret(client.key_pem_encrypted)
    tls_crypt = decrypt_secret(ca.tls_crypt_key_encrypted)

    # Plain repeated remote lines, not <connection> blocks: options that follow a
    # connection block are silently ignored by OpenVPN 2.x, which would drop
    # tls-crypt and leave the profile unusable. The client tries these in order,
    # so UDP comes first — it is faster, and TCP-in-TCP degrades badly on loss.
    remotes = f"remote {node.address} {node.openvpn_port} {node.openvpn_proto}"
    if node.tcp_port:
        remotes += f"\nremote {node.address} {node.tcp_port} tcp"

    return f"""# Aeolus · {client.common_name} via {node.name}
client
dev tun
{remotes}
# Move on to the next remote instead of retrying a transport the network mangles.
connect-retry-max 2
server-poll-timeout 12
resolv-retry infinite
nobind
persist-key
persist-tun
remote-cert-tls server
{_cipher_lines(data_cipher(node))}
tls-version-min 1.2
verb 3

<ca>
{ca.cert_pem.strip()}
</ca>
<cert>
{client.cert_pem.strip()}
</cert>
<key>
{key_pem.strip()}
</key>
<tls-crypt>
{tls_crypt.strip()}
</tls-crypt>
"""


async def build_client_profile(session, client: Client) -> tuple[Node, str]:
    """The client's .ovpn and the hub it points at, however it is handed out."""
    node = await session.scalar(select(Node).where(Node.is_hub.is_(True)))
    if node is None:
        raise OpenVpnError("панель ещё не зарегистрировала себя как узел")
    ca = await pki.require_ca(session)
    return node, render_client_config(client, node, ca)


async def sync_local_crl(session) -> bool:
    """Refresh the CRL the local OpenVPN reads.

    Revocation is only real once the node has the new list, so this runs on
    every revoke rather than waiting for the next restart. Remote nodes will get
    the same file from the anemoi agent.
    """
    target = Path(settings.openvpn_config_dir)
    if not target.exists():
        return False

    crl_pem = await pki.build_crl(session)
    (target / "crl.pem").write_text(crl_pem)
    logger.warning("Refreshed CRL at %s", target / "crl.pem")
    return True


STATUS_DIR = Path("/run/openvpn")


def read_status(path: Path) -> tuple[list[dict], list[dict]]:
    """The CLIENT LIST and ROUTING TABLE of a server-mode status file.

    Missing or unreadable files read as empty: a listener that is not up has no
    sessions, which is exactly what the caller should show.
    """
    if not path.exists():
        return [], []
    try:
        lines = path.read_text().splitlines()
    except OSError:
        return [], []

    clients: list[dict] = []
    routes: list[dict] = []
    section = ""
    for line in lines:
        if line.startswith("OpenVPN CLIENT LIST"):
            section = "clients"
            continue
        if line.startswith("ROUTING TABLE"):
            section = "routes"
            continue
        if line.startswith("GLOBAL STATS") or line == "END":
            section = ""
            continue
        parts = line.split(",")
        if section == "clients" and len(parts) >= 5 and parts[0] != "Common Name":
            clients.append(
                {
                    "common_name": parts[0],
                    "real_address": parts[1],
                    "rx_bytes": int(parts[2]) if parts[2].isdigit() else 0,
                    "tx_bytes": int(parts[3]) if parts[3].isdigit() else 0,
                    "connected_since": parts[4],
                }
            )
        elif section == "routes" and len(parts) >= 2 and parts[0] != "Virtual Address":
            routes.append({"network": parts[0], "common_name": parts[1]})
    return clients, routes


def transit_sessions() -> set[str]:
    """Node names the hub currently holds a transit tunnel with.

    The agent reports its own health, which is why a node whose tunnel had
    collapsed still showed up green: the agent was fine, the tunnel was not.
    The hub knows better — a node either has a session here or it does not.
    """
    clients, _ = read_status(STATUS_DIR / "status-transit.log")
    return {entry["common_name"] for entry in clients}


def transit_routes() -> dict[str, list[str]]:
    """What the transit listener will route into each node's tunnel, by node name.

    This is OpenVPN's own view, built from the iroutes it actually accepted, so
    it is the place to check whether a node's LAN — or the default route for an
    exit — really leads into that node.
    """
    _, routes = read_status(STATUS_DIR / "status-transit.log")
    table: dict[str, list[str]] = {}
    for route in routes:
        table.setdefault(route["common_name"], []).append(route["network"])
    return table


def client_sessions() -> dict[str, dict]:
    """Live client sessions on the hub, by common name, from both listeners.

    The agent forwards the same numbers every few seconds, but reading the
    files directly is what lets the map tell a phone that connected a moment
    ago from one that left a minute ago.
    """
    sessions: dict[str, dict] = {}
    for proto, name in (("udp", "status.log"), ("tcp", "status-tcp.log")):
        clients, routes = read_status(STATUS_DIR / name)
        virtual = {route["common_name"]: route["network"] for route in routes}
        for entry in clients:
            sessions[entry["common_name"]] = {
                **entry,
                "proto": proto,
                "virtual_address": virtual.get(entry["common_name"], ""),
            }
    return sessions


async def sync_routing_plan(session) -> bool:
    """Write the routing plan the local supervisor applies.

    Runs on every change that can affect who may reach what — a grant, an exit,
    a client's status — because a rule that has not reached the kernel is not a
    rule at all.
    """
    from app.services import routing

    target = Path(settings.openvpn_config_dir)
    if not target.exists():
        return False

    plan = await routing.build_plan(session)
    path = target / "routing.json"
    rendered = routing.render(plan)
    if path.exists() and path.read_text() == rendered:
        return False

    path.write_text(rendered)
    path.chmod(0o644)
    logger.warning("Wrote routing plan %s to %s", plan["revision"], path)
    return True


def write_server_bundle(node: Node, ca: CertificateAuthority, crl_pem: str) -> Path:
    """Write everything the local OpenVPN process needs into the shared volume.

    Used for the panel's own node; remote nodes will get the same bundle pushed
    by the anemoi agent instead.
    """
    if node.server_cert_pem is None or node.server_key_pem_encrypted is None:
        raise OpenVpnError(f"node {node.name} has no server certificate")

    target = Path(settings.openvpn_config_dir)
    target.mkdir(parents=True, exist_ok=True)
    # Both listeners need their directory to exist before OpenVPN starts, even
    # when the agent has not filled them in yet.
    (target / "ccd").mkdir(exist_ok=True)
    (target / "ccd-tcp").mkdir(exist_ok=True)

    files = {
        "ca.crt": ca.cert_pem,
        "server.crt": node.server_cert_pem,
        "server.key": decrypt_secret(node.server_key_pem_encrypted),
        "tls-crypt.key": decrypt_secret(ca.tls_crypt_key_encrypted),
        "crl.pem": crl_pem,
    }
    if node.tcp_port:
        files["server-tcp.conf"] = render_server_config(
            node, proto="tcp", port=node.tcp_port
        )
    # Written last on purpose: the OpenVPN supervisor waits for this file and
    # starts as soon as it appears, so everything else must already be there.
    files["server.conf"] = render_server_config(node)

    # A rewritten server.conf changes nothing until OpenVPN reloads it: the
    # running process holds the old options in memory. The agent flags its own
    # rewrites; this covers the panel writing the bundle at startup, which is how
    # a new template reaches the local node.
    changed = any(
        not (target / name).exists() or (target / name).read_text() != content
        for name, content in files.items()
        if name.endswith(".conf")
    )

    for name, content in files.items():
        path = target / name
        path.write_text(content)
        # Private material must not be world-readable inside the shared volume.
        path.chmod(0o600 if name in {"server.key", "tls-crypt.key"} else 0o644)

    if changed:
        (target / ".restart").write_text(str(time.time()))
        logger.warning("Server config changed, asked the supervisor to restart OpenVPN")

    logger.warning("Wrote OpenVPN bundle for node %r to %s", node.name, target)
    return target
